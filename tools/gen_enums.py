#!/usr/bin/env python3
"""gen_enums.py <isaac-typescript-definitions/src/enums> <out.lua> [<IsaacDocs/docs/enums> <out_docs.lua>]: the PC game's id
enums as Lua tables.

Names follow the game's own enums.lua: the TypeScript member name with the vanilla prefix
(SAD_ONION -> COLLECTIBLE_SAD_ONION). Where vanilla drops underscores (PICKUP_TAROTCARD), the
name without them is added too (only where vanilla has no other name for the value). Vanilla names that differ otherwise are in RENAME; small enums
whose vanilla names differ a lot are written by hand in src/prelude.lua.

IsaacDocs (github.com/wofsauge/IsaacDocs) lists the vanilla enums.lua names themselves (BIG_CRACKWAVE, HeartSubType...): names
and whole tables found only there go to <out_docs.lua>, which runs after prelude.lua and api.lua and only adds
names those and the generated tables lack."""
import re, sys

ENUMS = [  # (ts file, ts enum, Lua table, prefix, last+1 entry)
    ('collections/subTypes.ts', 'CollectibleType', 'CollectibleType', 'COLLECTIBLE_', 'NUM_COLLECTIBLES'),
    ('collections/subTypes.ts', 'TrinketType', 'TrinketType', 'TRINKET_', 'NUM_TRINKETS'),
    ('collections/subTypes.ts', 'PlayerType', 'PlayerType', 'PLAYER_', 'NUM_PLAYER_TYPES'),
    ('collections/subTypes.ts', 'PillColor', 'PillColor', 'PILL_', 'NUM_PILLS'),
    ('collections/subTypes.ts', 'CardType', 'Card', 'CARD_', 'NUM_CARDS'),
    ('collections/variants.ts', 'PickupVariant', 'PickupVariant', 'PICKUP_', None),
    ('collections/variants.ts', 'EffectVariant', 'EffectVariant', '', None),
    ('collections/variants.ts', 'FamiliarVariant', 'FamiliarVariant', '', None),
    ('collections/variants.ts', 'SlotVariant', 'SlotVariant', '', None),
    ('EntityType.ts', 'EntityType', 'EntityType', 'ENTITY_', None),
    ('PillEffect.ts', 'PillEffect', 'PillEffect', 'PILLEFFECT_', 'NUM_PILL_EFFECTS'),
    ('RoomType.ts', 'RoomType', 'RoomType', 'ROOM_', 'NUM_ROOMTYPES'),
    ('ItemPoolType.ts', 'ItemPoolType', 'ItemPoolType', 'POOL_', 'NUM_ITEMPOOLS'),
    ('Challenge.ts', 'Challenge', 'Challenge', 'CHALLENGE_', 'NUM_CHALLENGES'),
    ('GridEntityType.ts', 'GridEntityType', 'GridEntityType', 'GRID_', None),
    ('ItemType.ts', 'ItemType', 'ItemType', 'ITEM_', None),
    ('ActiveSlot.ts', 'ActiveSlot', 'ActiveSlot', 'SLOT_', None),
    ('Keyboard.ts', 'Keyboard', 'Keyboard', 'KEY_', None),
    ('SoundEffect.ts', 'SoundEffect', 'SoundEffect', 'SOUND_', None),
    ('Music.ts', 'Music', 'Music', 'MUSIC_', None),
    ('SeedEffect.ts', 'SeedEffect', 'SeedEffect', 'SEED_', 'NUM_SEEDS'),
    ('BackdropType.ts', 'BackdropType', 'BackdropType', '', 'NUM_BACKDROPS'),
    ('EntityCollisionClass.ts', 'EntityCollisionClass', 'EntityCollisionClass', 'ENTCOLL_', None),
    ('EntityGridCollisionClass.ts', 'EntityGridCollisionClass', 'EntityGridCollisionClass', 'GRIDCOLL_', None),
]
DIGITS = ['ZERO', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE']
RENAME = {**{('Keyboard', d): 'KEY_%d' % i for i, d in enumerate(DIGITS)},
          ('CollectibleType', 'NULL'): 'COLLECTIBLE_NULL', ('PlayerType', 'POSSESSOR'): 'PLAYER_POSSESSOR',
          ('PickupVariant', 'CARD'): 'PICKUP_TAROTCARD'}
# vanilla names the rules above do not produce (added next to the generated ones)
EXTRA = {'PlayerType': {'PLAYER_XXX': 4, 'PLAYER_THELOST': 10, 'PLAYER_BLACKJUDAS': 12, 'PLAYER_THEFORGOTTEN': 16,
                        'PLAYER_THESOUL': 17, 'PLAYER_XXX_B': 25, 'PLAYER_BLUEBABY_B': 25, 'PLAYER_THELOST_B': 31,
                        'PLAYER_THEFORGOTTEN_B': 35, 'PLAYER_LAZARUS2_B': 38, 'PLAYER_JACOB2_B': 39,
                        'PLAYER_THESOUL_B': 40}}
SUITS = {'CLUBS', 'DIAMONDS', 'SPADES', 'HEARTS'}

def members(src, name):
    m = re.search(r'export enum %s \{(.*?)\n\}' % name, src, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    body = re.sub(r'//[^\n]*', '', body)
    for k, v in re.findall(r'(\w+)\s*=\s*(-?\d+)', body):
        yield k, int(v)

def names(lua, prefix, k):
    if (lua, k) in RENAME: return [RENAME[(lua, k)]]
    if lua == 'Card':
        if k.startswith('RUNE_'): return [k]
        if k.startswith('SOUL_OF_'): return ['CARD_SOUL_' + k[8:]]
        m = re.match(r'(TWO|ACE)_OF_(\w+)$', k)
        if m and m.group(2) in SUITS:  # vanilla CARD_CLUBS_2, CARD_ACE_OF_CLUBS
            return ['CARD_%s_2' % m.group(2)] if m.group(1) == 'TWO' else ['CARD_' + k]
    n = [prefix + k]
    if '_' in k and lua in ('PickupVariant', 'RoomType', 'Challenge', 'PlayerType', 'ItemPoolType', 'GridEntityType',
                                'EntityCollisionClass', 'EntityGridCollisionClass'):
        n.append(prefix + k.replace('_', ''))
    return n

out = ['-- generated by tools/gen_enums.py from isaac-typescript-definitions (MIT); do not edit']
for f, ts, lua, prefix, num in ENUMS:
    src = open(sys.argv[1] + '/' + f).read()
    out.append('%s = {' % lua)
    seen, top = set(), -1
    for k, v in members(src, ts):
        if v < 2048: top = max(top, v)  # pill colors: the horse-pill flag is not a member
        for n in names(lua, prefix, k):
            if n in seen: continue
            seen.add(n)
            out.append('  %s = %d,' % (n, v))
    for n, v in EXTRA.get(lua, {}).items():
        if n not in seen: out.append('  %s = %d,' % (n, v))
    if num: out.append('  %s = %d,' % (num, top + 1))
    if lua == 'PillColor': out += ['  NUM_STANDARD_PILLS = %d,' % top, '  PILL_GIANT_FLAG = 2048,']
    if lua == 'TrinketType': out += ['  TRINKET_GOLDEN_FLAG = 32768,', '  TRINKET_ID_MASK = 32767,']
    out.append('}')
# bit-flag objects (flags/*.ts, "NAME: 1 << n"): vanilla prefix, also without underscores
FLAGS = [('EntityFlag', 'EntityFlag', 'FLAG_'), ('DamageFlag', 'DamageFlag', 'DAMAGE_'),
         ('RoomDescriptorFlag', 'RoomDescriptor', 'FLAG_')]  # vanilla RoomDescriptor.FLAG_RED_ROOM
for f, lua, prefix in FLAGS:
    src = open(sys.argv[1] + '/flags/%s.ts' % f).read()
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    out.append('%s = {' % lua)
    seen = set()
    for k, v in re.findall(r'(\w+):\s*1 << (\d+)', src):
        for n in (prefix + k, prefix + k.replace('_', '')):
            if n not in seen:
                seen.add(n)
                out.append('  %s = %d,' % (n, 1 << int(v)))
    out.append('}')
# IsaacDocs tables: rows "|<dlc badge>|<value> |<NAME> {: .copyable } |<comment>", value an integer or "1 << n";
# a comment "(legacy: OLD)" or "(ab+: OLD)" names an older spelling vanilla still has (PLAYER_MAGDALENA_B)
DOCS_SKIP = {'ModCallbacks', 'TearFlags'}  # callbacks are in prelude.lua; tear flags are BitSet128 there
docs = ['-- generated by tools/gen_enums.py from IsaacDocs (github.com/wofsauge/IsaacDocs); do not edit']
if len(sys.argv) > 4:
    import os
    # a name vanilla lacks where vanilla has another one for the same value (ROOM_SUPER_SECRET next to
    # ROOM_SUPERSECRET) goes: mods walk these tables with pairs() and look each name up in their own tables
    vanilla = {}
    for f in os.listdir(sys.argv[3]):
        if not f.endswith('.md'): continue
        for v, k, rest in re.findall(r'^\|[^|]*\|\s*(-?\d+|1\s*<<\s*\d+)\s*\|\s*(\w+) \{: \.copyable \}(.*)$',
                                    open(os.path.join(sys.argv[3], f)).read(), re.M):
            v = 1 << int(v.split('<<')[1]) if '<<' in v else int(v)
            vanilla.setdefault(f[:-3], {}).setdefault(v, set()).update(
                [k] + re.findall(r'\((?:legacy|ab\+):\s*(\w+)\)', rest, re.I))
    kept, cur = [], None
    for line in out:
        m = re.match(r'(\w+) = \{$', line)
        if m: cur = vanilla.get(m.group(1))
        m = re.match(r'  (\w+) = (-?\d+),$', line)
        if m and cur and int(m.group(2)) in cur and m.group(1) not in cur[int(m.group(2))]: continue
        kept.append(line)
    out = kept
    tables = {}
    cur = None
    for line in out:
        m = re.match(r'(\w+) = \{$', line)
        if m: cur = tables.setdefault(m.group(1), set())
        m = re.match(r'  (\w+) = ', line)
        if m and cur is not None: cur.add(m.group(1))
    for f in sorted(os.listdir(sys.argv[3])):
        lua = f[:-3]
        if not f.endswith('.md') or lua in DOCS_SKIP: continue
        rows = []
        for v, k, rest in re.findall(r'^\|[^|]*\|\s*(-?\d+|1\s*<<\s*\d+)\s*\|\s*(\w+) \{: \.copyable \}(.*)$',
                                    open(os.path.join(sys.argv[3], f)).read(), re.M):
            v = 1 << int(v.split('<<')[1]) if '<<' in v else int(v)
            for n in [k] + re.findall(r'\((?:legacy|ab\+):\s*(\w+)\)', rest, re.I):
                if n not in tables.get(lua, ()) and n not in [r[0] for r in rows]: rows.append((n, v))
        if not rows: continue
        docs.append('%s = %s or {}' % (lua, lua))
        docs += ["if rawget(%s, '%s') == nil then %s.%s = %d end" % (lua, k, lua, k, v) for k, v in rows]
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
if len(sys.argv) > 4: open(sys.argv[4], 'w').write('\n'.join(docs) + '\n')
